using System;
using StadionTracking;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

internal static class TreadmillOvalSetup
{
    private const string MeshPath = "Assets/TreadmillPrototype/Oval400m.asset";

    [MenuItem("Tools/Treadmill/Use 400m oval track")]
    public static void ConfigureScene()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
            throw new InvalidOperationException("Exit Play mode first.");
        var world = UnityEngine.Object.FindFirstObjectByType<StraightTreadmillWorld>();
        if (world == null) throw new InvalidOperationException("Open the treadmill test scene first.");
        Mesh generated = CreateMesh();
        Mesh mesh = AssetDatabase.LoadAssetAtPath<Mesh>(MeshPath);
        if (mesh == null) { AssetDatabase.CreateAsset(generated, MeshPath); mesh = generated; }
        else { EditorUtility.CopySerialized(generated, mesh); UnityEngine.Object.DestroyImmediate(generated); }
        var material = AssetDatabase.LoadAssetAtPath<Material>("Assets/TreadmillPrototype/TreadmillUnlit.mat");
        if (material == null) throw new InvalidOperationException("Track material is missing.");
        // Replace only geometry generated by the treadmill prototype.
        for (int i = world.transform.childCount - 1; i >= 0; i--)
        {
            GameObject child = world.transform.GetChild(i).gameObject;
            if (child.name.StartsWith("Track tile ") || child.name == "400m track")
                UnityEngine.Object.DestroyImmediate(child);
        }
        var track = new GameObject("400m track");
        track.transform.SetParent(world.transform, false);
        track.AddComponent<MeshFilter>().sharedMesh = mesh;
        track.AddComponent<MeshRenderer>().sharedMaterial = material;

        world.transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
        var data = new SerializedObject(world);
        data.FindProperty("followOval400m").boolValue = true;
        data.FindProperty("ovalStartMetres").floatValue = 390f;
        data.ApplyModifiedPropertiesWithoutUndo();
        world.ResetDistance();
        data.Update();
        data.FindProperty("placementReady").boolValue = false;
        data.ApplyModifiedPropertiesWithoutUndo();
        StraightTreadmillSetup.UseFixedHeight();
        EditorUtility.SetDirty(mesh);
        EditorSceneManager.MarkSceneDirty(world.gameObject.scene);
        EditorSceneManager.SaveScene(world.gameObject.scene);
        AssetDatabase.SaveAssets();
        Selection.activeGameObject = world.gameObject;
        SceneView.lastActiveSceneView?.LookAt(new Vector3(0, 0, 20), Quaternion.Euler(45, 0, 0), 55f);
        Debug.Log("[Treadmill] 400 m oval ready: eight lanes, closed bends, start 10 m before the bend. " +
            "Fixed height 184 cm; speed remains unchanged.");
    }

    private static Mesh CreateMesh()
    {
        const int steps = 1024;
        var geometry = new StadiumTrackGeometry();
        var builder = new TrackMeshBuilder();
        Vector3 Edge(double metres, float offset, float y)
        {
            var p = geometry.Evaluate(1, metres);
            return new Vector3((float)p.X + (float)p.DirectionZ * offset, y,
                (float)p.Z - (float)p.DirectionX * offset);
        }
        void Strip(double s0, double s1, float inner, float outer, float y, Color color) =>
            builder.AddQuad(Edge(s0, inner, y), Edge(s1, inner, y), Edge(s1, outer, y), Edge(s0, outer, y), color);

        double length = geometry.Length(1);
        float width = (float)(StadiumTrackGeometry.LaneWidth * StadiumTrackGeometry.LaneCount);
        for (int i = 0; i < steps; i++)
        {
            double s0 = i * length / steps, s1 = (i + 1) * length / steps;
            // Leave the real floor visible between the lane markings.
            for (int lane = 0; lane <= StadiumTrackGeometry.LaneCount; lane++)
            {
                float offset = (float)(lane * StadiumTrackGeometry.LaneWidth) - 0.3f;
                Strip(s0, s1, offset - 0.025f, offset + 0.025f, 0.005f, Color.white);
            }
        }
        // Short 10 m edge ticks make motion visible without adding a HUD or scenery.
        for (int i = 0; i < 40; i++)
        {
            double s = i * length / 40;
            Strip(s, s + 0.12, -0.28f, -0.02f, 0.009f, Color.yellow);
            Strip(s, s + 0.12, width - 0.58f, width - 0.32f, 0.009f, Color.yellow);
        }
        double start = 390.0 * length / 400.0;
        Strip(start, start + 0.12, -0.3f, width - 0.3f, 0.01f, Color.white);
        return builder.CreateMesh("400m oval - 8 lanes");
    }

    [MenuItem("Tools/Treadmill/Verify 400m oval motion")]
    public static void VerifyMotion()
    {
        if (EditorApplication.isPlaying) throw new InvalidOperationException("Run outside Play mode.");
        var go = new GameObject("Temporary oval verification");
        var head = new GameObject("Temporary head");
        try
        {
            var world = go.AddComponent<StraightTreadmillWorld>();
            Camera camera = head.AddComponent<Camera>();
            head.transform.SetPositionAndRotation(new Vector3(3, 1.72f, 7), Quaternion.Euler(0, 28, 0));
            var data = new SerializedObject(world);
            data.FindProperty("headCamera").objectReferenceValue = camera;
            data.FindProperty("followOval400m").boolValue = true;
            data.FindProperty("requireHeightCalibration").boolValue = false;
            data.ApplyModifiedPropertiesWithoutUndo();
            world.AlignToCurrentView();
            Vector3 initialPosition = go.transform.position;
            Quaternion initialRotation = go.transform.rotation;
            Vector3 belt = new Vector3(3, 0, 7);
            var geometry = new StadiumTrackGeometry();
            world.SpeedKmh = 36;
            for (int i = 0; i < 400; i++)
            {
                world.AdvanceSimulation(0.1f);
                var p = geometry.Evaluate(1, (390.0 + world.TravelledMetres % 400.0) * geometry.Length(1) / 400.0);
                Vector3 mapped = go.transform.TransformPoint(new Vector3((float)p.X, 0, (float)p.Z));
                Vector3 tangent = go.transform.TransformDirection(new Vector3((float)p.DirectionX, 0, (float)p.DirectionZ));
                Check(Vector3.Distance(mapped, belt) < 0.0001f, "virtual running point stays on physical belt");
                Check(Vector3.Angle(tangent, head.transform.forward) < 0.03f, "curve tangent stays forward");
                Check(head.transform.position == new Vector3(3, 1.72f, 7), "head position untouched");
                if (i == 29) Check(Quaternion.Angle(initialRotation, go.transform.rotation) > 20f, "world turns in bend");
            }
            Check(Math.Abs(world.TravelledMetres - 400) < 0.0001, "400 m distance");
            Check(world.CompletedLaps == 1, "lap wraps at 400 m");
            Check(Vector3.Distance(go.transform.position, initialPosition) < 0.001f, "lap closes without jump");
            Check(Quaternion.Angle(go.transform.rotation, initialRotation) < 0.03f, "lap heading closes");
            world.SpeedKmh = 0;
            Vector3 paused = go.transform.position;
            Quaternion pausedRotation = go.transform.rotation;
            world.AdvanceSimulation(30);
            Check(go.transform.position == paused && go.transform.rotation == pausedRotation, "pause freezes translation and rotation");
            world.ResetDistance();
            Check(world.TravelledMetres == 0 && Vector3.Distance(go.transform.position, initialPosition) < 0.001f, "reset restores oval start");
            Debug.Log("[Treadmill] PASS: 400 m oval, continuous belt position and heading through all bends, lap closure, pause and reset.");
        }
        finally { UnityEngine.Object.DestroyImmediate(go); UnityEngine.Object.DestroyImmediate(head); }
    }

    private static void Check(bool passed, string label)
    {
        if (!passed) throw new InvalidOperationException("[Treadmill oval] FAIL: " + label);
    }
}
